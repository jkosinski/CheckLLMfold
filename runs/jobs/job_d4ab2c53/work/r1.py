from rounds import *

def base(cs):
    cs.anti(18, 1, 7, 1.0, 11, 17)        # strand 1-7 antiparallel with 11-17 (turn 8-10)
    cs.par(62, 1, 7, 0.95, 63, 71)        # strand 1-7 parallel with 63-70
    cs.anti(112, 40, 45, 0.95, 66, 72)    # strand 40-45 antiparallel with 67-72
    cs.anti(93, 42, 45, 0.8, 48, 51)      # 42-45 / 48-51 tight hairpin
    cs.helix(23, 34)
    cs.helix(56, 60, 0.7)
    for i, j in [(8, 11), (7, 10), (45, 48), (51, 54), (52, 55), (18, 21), (19, 22), (35, 38), (37, 40), (62, 65), (72, 75)]:
        cs.add(i, j, 0.5)

