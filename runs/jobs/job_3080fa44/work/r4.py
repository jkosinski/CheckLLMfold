from lib import *
T = {}   # contact -> tier (lower = more confident)
def add(pairs, tier):
    for i, j in pairs:
        i, j = min(i, j), max(i, j)
        if j - i < 3 or not (1 <= i and j <= L): continue
        T[(i, j)] = min(tier, T.get((i, j), 99))

# strand ladders: exact register first, diagonal neighbours next
